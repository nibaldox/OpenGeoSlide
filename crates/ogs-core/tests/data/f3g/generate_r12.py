#!/usr/bin/env python3
"""Adds the rows of R12 (E15l-10, A-11): ponded water that is active on the analysed surface.

`X21-CP-V042` and `X21-CP-V061` are `pond` rows whose surface gets no ponded term (the piezometric line is under the
ground along it: Σ|weight_extra| = Σ|h_force| = 0). These rows take the same models with a circle that does cross the
water, and keep the oracle figure of cSlope 0.1.0 for each method. Run from the repository root with the Python of the
oracle (it needs `cslope`, `shapely` and `verification/harness`):

    $TMPDIR/oracle-venv/bin/python crates/ogs-core/tests/data/f3g/generate_r12.py

It writes `r12/rows/*.json` and `r12/expected.json`. The oracle is run like `verification/harness/run.py` does: one
check per method on the fixed surface, converted by `to_cslope.py`; Spencer and Morgenstern-Price share the figure of
cSlope's Spencer (E8). The test is `f3g_rows.rs` (`r12_*`).
"""
import copy
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[4]
sys.path.insert(0, str(ROOT / "verification/harness"))

import cslope  # noqa: E402
from run import model_for_check, run_cslope  # noqa: E402
from to_cslope import ogs_to_cslope  # noqa: E402

METHODS = ["bishop", "spencer", "morgenstern_price", "janbu_simplified", "janbu_corrected"]

# id -> (base row, patch of the analysis, description)
ROWS = {
    "X21-R12-V042-up": (
        "X21-CP-V042",
        {"surface": {"type": "circle", "xc": 110.0, "yc": 190.0, "r": 125.0}},
        "V042, circulo fijo por el talud de aguas arriba: atraviesa el embalse (peso y empuje del agua sobre la superficie)",
    ),
    "X21-R12-V042-up-kh": (
        "X21-CP-V042",
        {"surface": {"type": "circle", "xc": 110.0, "yc": 190.0, "r": 125.0}, "seismic": {"kh": 0.1}},
        "ídem con kh = 0,1 (el agua embalsada no recibe fuerza sísmica, E7)",
    ),
    "X21-R12-V061-der": (
        "X21-CP-V061",
        {"surface": {"type": "circle", "xc": 60.0, "yc": 320.0, "r": 170.0}},
        "V061, círculo fijo que sale por el lado derecho, bajo el agua (1,28 m sobre el terreno)",
    ),
}


def oracle(doc):
    out = {}
    for m in METHODS:
        if m not in doc["analysis"]["methods"]:
            continue
        check = {"method": "spencer" if m == "morgenstern_price" else m, "kind": "fixed", "published": 1.0, "tolerance": 0.05}
        model = model_for_check(doc, check)
        res = run_cslope(cslope, ogs_to_cslope(model, check).document)
        assert res["fos"] is not None, (m, res["error"])
        out[m] = res["fos"]
    return out


def main():
    (HERE / "r12" / "rows").mkdir(parents=True, exist_ok=True)
    rows = {}
    for rid, (base, patch, description) in ROWS.items():
        doc = json.loads((HERE / "rows" / f"{base}.json").read_text())
        doc["meta"] = {"id": rid, "title": description}
        doc["analysis"].update(copy.deepcopy(patch))
        # Bishop only on a circle, and only if the base row has it.
        (HERE / "r12" / "rows" / f"{rid}.json").write_text(json.dumps(doc, indent=1) + "\n")
        rows[rid] = {"kind": "pond", "base": base, "description": description, "oracle": oracle(doc)}
    expected = {
        "source": "oracle cSlope 0.1.0 (verification/harness/to_cslope.py + run.py), generated by generate_r12.py",
        "tolerance_pct": 0.1,
        "rows": rows,
    }
    (HERE / "r12" / "expected.json").write_text(json.dumps(expected, indent=1) + "\n")
    print(len(rows), "rows")


if __name__ == "__main__":
    main()
